// Command gen-editors regenerates every consumer of cljgo's defining forms
// from the single source of truth, tooling/definers.json.
//
// Clojure is homoiconic: a definition has no node type of its own, so every
// tool that wants to find one needs the same list of head symbols. Editors
// need it to highlight and indent; ctx-optimize needs it to emit declaration
// nodes. Four hand-maintained copies drift; this generates all four.
//
//	go run ./tooling/gen-editors          # write
//	go run ./tooling/gen-editors -check   # verify in sync (CI)
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type definer struct {
	Head   string `json:"head"`
	Kind   string `json:"kind"`
	Indent string `json:"indent"`
	ADR    string `json:"adr,omitempty"`
	// QuotedName: the name is a quoted symbol — `(in-ns 'bri.cli)`. Only
	// ctx-optimize cares; editors highlight the head either way.
	QuotedName bool `json:"quoted_name,omitempty"`
}

// qualified reports a namespace-qualified head such as `clojure.core/in-ns`.
// The editor outputs skip these: the tree-sitter query matches on `!namespace`
// so a qualified symbol cannot match it, and `put-clojure-indent` takes a bare
// symbol. ctx-optimize matches head text exactly, so it keeps them.
func qualified(head string) bool { return strings.Contains(head, "/") }

type spec struct {
	Core       []definer `json:"clojure_core"`
	Bri        []definer `json:"bri"`
	SkipInside []string  `json:"skip_inside"`
	Exts       []string  `json:"exts"`
}

func (s spec) all() []definer { return append(append([]definer{}, s.Core...), s.Bri...) }

const banner = "GENERATED by tooling/gen-editors from tooling/definers.json — do not edit by hand."

func main() {
	check := flag.Bool("check", false, "verify generated files are in sync instead of writing")
	flag.Parse()

	root, err := repoRoot()
	must(err)
	raw, err := os.ReadFile(filepath.Join(root, "tooling", "definers.json"))
	must(err)
	var s spec
	must(json.Unmarshal(raw, &s))
	if len(s.all()) == 0 {
		must(fmt.Errorf("definers.json defines no forms"))
	}

	out := map[string][]byte{
		"tooling/tree-sitter/generated/definers.scm":     tsQuery(s),
		"tooling/editors/emacs/generated/definers.el":    elisp(s),
		"tooling/editors/vscode/generated/definers.json": tmGrammar(s),
		".ctxoptimize/grammars/cljgo.json":               pack(s),
	}

	paths := make([]string, 0, len(out))
	for p := range out {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	stale := 0
	for _, rel := range paths {
		abs := filepath.Join(root, rel)
		if *check {
			cur, err := os.ReadFile(abs)
			if err != nil || string(cur) != string(out[rel]) {
				fmt.Printf("STALE %s\n", rel)
				stale++
			}
			continue
		}
		must(os.MkdirAll(filepath.Dir(abs), 0o755))
		must(os.WriteFile(abs, out[rel], 0o644))
		fmt.Printf("wrote %s\n", rel)
	}
	if *check {
		if stale > 0 {
			fmt.Fprintf(os.Stderr, "\n%d file(s) stale — run: go run ./tooling/gen-editors\n", stale)
			os.Exit(1)
		}
		fmt.Println("generated files in sync")
	}
}

// heads returns the head symbols, regex-escaped, longest first so that
// alternation matches `defn-` before `defn` and `defroutes` before `defroute`.
func heads(ds []definer) []string {
	out := make([]string, 0, len(ds))
	for _, d := range ds {
		if qualified(d.Head) {
			continue
		}
		out = append(out, d.Head)
	}
	sort.Slice(out, func(i, j int) bool {
		if len(out[i]) != len(out[j]) {
			return len(out[i]) > len(out[j])
		}
		return out[i] < out[j]
	})
	return out
}

func escape(s string) string {
	r := strings.NewReplacer("-", "\\-", "?", "\\?", "!", "\\!", "*", "\\*", "+", "\\+", ".", "\\.")
	return r.Replace(s)
}

// tsQuery emits a highlights fragment for nvim / Helix / Zed. Portable: only
// #match? and a negated field, per tooling/tree-sitter/README.md.
func tsQuery(s spec) []byte {
	esc := make([]string, 0)
	for _, h := range heads(s.all()) {
		esc = append(esc, escape(h))
	}
	var b strings.Builder
	fmt.Fprintf(&b, ";; %s\n;;\n", banner)
	b.WriteString(";; Every defining form cljgo knows, as @keyword in head position.\n")
	b.WriteString(";; Layer with `;; extends` in nvim's after/queries/clojure/.\n\n")
	fmt.Fprintf(&b, "(list_lit\n  .\n  (sym_lit\n    !namespace\n    name: (sym_name) @keyword\n    (#match? @keyword \"^(%s)$\")))\n", strings.Join(esc, "|"))
	return []byte(b.String())
}

func elisp(s spec) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, ";;; definers.el --- %s  -*- lexical-binding: t; -*-\n\n;;; Commentary:\n;; Indent rules for every cljgo defining form.\n\n;;; Code:\n\n(require 'clojure-mode nil t)\n\n(defun cljgo--apply-definer-indents ()\n  \"Apply `defun'-style indentation to cljgo's defining forms.\"\n", banner)
	for _, d := range s.all() {
		if qualified(d.Head) {
			continue
		}
		fmt.Fprintf(&b, "  (put-clojure-indent '%s '%s)\n", d.Head, d.Indent)
	}
	b.WriteString(")\n\n(provide 'definers)\n;;; definers.el ends here\n")
	return []byte(b.String())
}

// tmGrammar emits a TextMate INJECTION grammar. VS Code merges an injection
// into the host scope, so definers stay generated without the hand-maintained
// cljgo.tmLanguage.json having to be rewritten. Wired via the second
// "grammars" entry (injectTo: source.cljgo) in package.json.
func tmGrammar(s spec) []byte {
	alt := strings.Join(heads(s.all()), "|")
	doc := map[string]any{
		"_generated":        banner,
		"scopeName":         "cljgo.definers.injection",
		"injectionSelector": "L:source.cljgo",
		"patterns": []any{map[string]any{
			"comment": "every cljgo defining form in head position",
			"match":   `(?<=\()(` + alt + `)(?=[\s)])`,
			"name":    "keyword.control.definer.cljgo",
		}},
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	must(err)
	return append(out, '\n')
}

// pack emits the ctx-optimize grammar pack. decl_rules (not decls) because a
// Clojure declaration has no node type: match the head symbol literally, read
// the name from the next symbol, and skip quoted forms.
func pack(s spec) []byte {
	plain, quoted := map[string]string{}, map[string]string{}
	for _, d := range s.all() {
		if d.QuotedName {
			quoted[d.Head] = d.Kind
		} else {
			plain[d.Head] = d.Kind
		}
	}
	rules := []any{map[string]any{
		"node":        "list_lit",
		"head_type":   "sym_lit",
		"name_type":   "sym_lit",
		"skip_inside": s.SkipInside,
		"head_match":  plain,
	}}
	// Quoted-name forms need their own rule: `(in-ns 'bri.cli)` wraps the
	// name in a quoting_lit that must be stepped over first.
	if len(quoted) > 0 {
		rules = append(rules, map[string]any{
			"node":        "list_lit",
			"head_type":   "sym_lit",
			"name_type":   "sym_lit",
			"name_unwrap": []string{"quoting_lit", "syn_quoting_lit"},
			"skip_inside": s.SkipInside,
			"head_match":  quoted,
		})
	}
	doc := map[string]any{
		"_generated": banner,
		"name":       "cljgo",
		"exts":       s.Exts,
		"decl_rules": rules,
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	must(err)
	return append(out, '\n')
}

func repoRoot() (string, error) {
	d, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(d, "tooling", "definers.json")); err == nil {
			return d, nil
		}
		p := filepath.Dir(d)
		if p == d {
			return "", fmt.Errorf("tooling/definers.json not found above %s", d)
		}
		d = p
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-editors:", err)
		os.Exit(1)
	}
}
